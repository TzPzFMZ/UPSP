def feeling_words(domain):
    table = INTERACTION_PROTOCOL_TABLE if domain == "interaction" else RELATION_PROTOCOL_TABLE
    return tuple(table)


def build_feeling_guide():
    """渲染 memory_write 的近位词清单，不暴露数值。"""
    parts = ["## memory_write 感受词清单（仅词条，不含数值）"]
    for label, table, limit in (
        ("交互感受词", INTERACTION_PROTOCOL_TABLE, "每条记忆最多选 3 个。"),
        ("关系感受词", RELATION_PROTOCOL_TABLE, "每个对象最多选 2 个。"),
    ):
        parts.extend((f"### {label}", f"- 约束：{limit}"))
        for layer, layer_label in LAYER_LABELS.items():
            words = [word for word, entry in table.items() if entry["layer"] == layer]
            parts.append(f"- {layer_label}: {'、'.join(words)}")
    return "\n".join(parts)


class FeelingWordTable:
    """只读感受词查询与逐轴合并。"""

    interaction = INTERACTION_PROTOCOL_TABLE
    relation = RELATION_PROTOCOL_TABLE

    @staticmethod
    def _result(word, entry):
        if not entry:
            return None
        return {"word": word, "layer": entry["layer"], "deltas": dict(entry["deltas"])}

    def lookup_interaction(self, words):
        results = []
        for value in words or []:
            word = str(value or "").strip()
            result = self._result(word, self.interaction.get(word))
            if result:
                results.append(result)
        return results[:INTERACTION_FEELINGS_MAX_PER_ROUND]

    def lookup_relation(self, word):
        word = str(word or "").strip()
        return self._result(word, self.relation.get(word))

    @staticmethod
    def merge_deltas(lookup_results):
        merged = {}
        for result in lookup_results or []:
            for axis, delta in result.get("deltas", {}).items():
                merged[axis] = merged.get(axis, 0) + delta
        return merged


