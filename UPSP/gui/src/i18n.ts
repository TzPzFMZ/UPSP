export type MessageKey = keyof typeof english;

export function systemLocale(languages: readonly string[] = typeof navigator === "undefined" ? [] : navigator.languages): Locale {
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (normalized.startsWith("zh")) return "zh-CN";
    if (normalized.startsWith("en")) return "en-US";
  }
  return "zh-CN";
}

export function initialLocale(
  languages: readonly string[] = typeof navigator === "undefined" ? [] : navigator.languages,
): Locale {
  return systemLocale(languages);
}

let activeLocale: Locale = initialLocale();

export function locale(): Locale {
  return activeLocale;
}

export function setLocale(next: Locale): void {
  activeLocale = next;
}

export function configuredLocale(
  value: unknown,
  languages: readonly string[] = typeof navigator === "undefined" ? [] : navigator.languages,
): Locale {
  return value === "zh-CN" || value === "en-US" ? value : systemLocale(languages);
}

export function t(key: MessageKey, values: Record<string, unknown> = {}): string {
  let text: string = activeLocale === "zh-CN" ? key : english[key];
  for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function applyStaticTranslations(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n as MessageKey);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel as MessageKey));
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => {
    element.title = t(element.dataset.i18nTitle as MessageKey);
  });
  root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder as MessageKey);
  });
}

